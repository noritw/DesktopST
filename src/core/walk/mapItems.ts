const RARITY: Record<string, ItemRarity> = { c: 'common', u: 'uncommon', r: 'rare' }

export const MAP_ITEMS: readonly MapItem[] = (Object.keys(TABLE) as JourneyMapId[]).flatMap((map) =>
  TABLE[map]
    .trim()
    .split('\n')
    .map((line) => {
      const [code, name, look, move] = line.split('｜')
      const [a, n] = code.split('-')
      return { id: `${map}-${code}`, map, approach: a as Approach, rarity: RARITY[n[0]], name, look, move }
    })
)

const BY_ID = new Map(MAP_ITEMS.map((i) => [i.id, i]))
export const findMapItem = (id: string | undefined): MapItem | undefined => (id ? BY_ID.get(id) : undefined)

/** 過招與舊存檔都認分類，各做法取一個代表。 */
const CATEGORY_OF: Record<Approach, ItemCategory> = { lure: 'glow', move: 'ink', trap: 'vessel', startle: 'nature' }
export const kindIdOf = (i: MapItem): string => `${CATEGORY_OF[i.approach]}-${i.rarity[0]}1`

